"""A 股交易日历。"""

from __future__ import annotations
from datetime import date, timedelta
from functools import lru_cache

_HOLIDAYS = set()
for y, m, d in [
    (2024, 1, 1), (2024, 2, 9), (2024, 2, 10), (2024, 2, 11), (2024, 2, 12),
    (2024, 2, 13), (2024, 2, 14), (2024, 2, 15), (2024, 4, 4), (2024, 4, 5),
    (2024, 5, 1), (2024, 5, 2), (2024, 5, 3), (2024, 6, 10), (2024, 9, 16),
    (2024, 9, 17), (2024, 10, 1), (2024, 10, 2), (2024, 10, 3), (2024, 10, 4),
    (2024, 10, 7), (2025, 1, 1), (2025, 1, 28), (2025, 1, 29), (2025, 1, 30),
    (2025, 1, 31), (2025, 2, 3), (2025, 2, 4), (2025, 4, 4), (2025, 5, 1),
    (2025, 5, 2), (2025, 6, 2), (2025, 10, 1), (2025, 10, 2), (2025, 10, 3),
    (2025, 10, 6), (2025, 10, 7), (2025, 10, 8), (2026, 1, 1), (2026, 1, 2),
    (2026, 2, 16), (2026, 2, 17), (2026, 2, 18), (2026, 2, 19), (2026, 2, 20),
    (2026, 4, 6), (2026, 5, 1), (2026, 5, 4), (2026, 5, 5), (2026, 6, 19),
    (2026, 9, 25), (2026, 10, 1), (2026, 10, 2), (2026, 10, 5), (2026, 10, 6),
    (2026, 10, 7),
]:
    _HOLIDAYS.add(f"{y}-{m:02d}-{d:02d}")


@lru_cache(maxsize=64)
def is_trading_day(d: date) -> bool:
    if d.weekday() >= 5:
        return False
    return d.isoformat() not in _HOLIDAYS


def next_trading_day(d: date) -> date:
    d = d + timedelta(days=1)
    while not is_trading_day(d):
        d = d + timedelta(days=1)
    return d
